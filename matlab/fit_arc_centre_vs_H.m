% Example of the geometry curve fit (project report, Section 2.2.1).
% The x-coordinate of an arc centre was read from SolidWorks for
% H = 0.4 ... 2 mm (step 0.05 mm) and fitted with a 2nd-order polynomial.
% The same procedure was applied to every arc start, end and centre point.

centre_x = [6.4, 6.45, 6.5, 6.55, 6.6, 6.65, 6.7, 6.75, 6.8, 6.85, ...
            6.9, 6.95, 7, 7.05, 7.1, 7.15, 7.2, 7.25, 7.3, 7.35, ...
            7.4, 7.45, 7.5, 7.55, 7.6, 7.65, 7.7, 7.75, 7.8, 7.85, ...
            7.9, 7.95, 8];
h        = [0.4, 0.45, 0.5, 0.55, 0.6, 0.65, 0.7, 0.75, 0.8, 0.85, ...
            0.9, 0.95, 1, 1.05, 1.1, 1.15, 1.2, 1.25, 1.3, 1.35, ...
            1.4, 1.45, 1.5, 1.55, 1.6, 1.65, 1.7, 1.75, 1.8, 1.85, ...
            1.9, 1.95, 2];

p = polyfit(h, centre_x, 2);
disp('Polynomial coefficients:');
disp(p);
